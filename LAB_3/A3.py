# Считываем предыдущее и текущее показания счетчика
prev_val = int(input())
curr_val = int(input())

# Вычисляем объем использованного газа с учетом возможного сброса счетчика (после 9999 идет 0)
if curr_val >= prev_val:
    used = curr_val - prev_val
else:
    used = (10000 - prev_val) + curr_val

# Вычисляем стоимость по ступенчатому тарифу
cost = 0.0

if used <= 300:
    cost = 21.0
elif used <= 600:
    # Первые 300 кубов стоят фиксировано 21$, а всё, что свыше 300 до 600 — по 0.06$
    cost = 21.0 + (used - 300) * 0.06
elif used <= 800:
    # Первые 300 по 21$, след. 300 (от 300 до 600) по 0.06$, а остаток выше 600 — по 0.04$
    cost = 21.0 + 300 * 0.06 + (used - 600) * 0.04
else:
    # Свыше 800 кубов
    cost = 21.0 + 300 * 0.06 + 200 * 0.04 + (used - 800) * 0.025

# Вычисляем среднюю цену за кубометр (если расход 0, средняя цена тоже 0)
if used > 0:
    avg_price = cost / used
else:
    avg_price = 0.0

print(f"{'Предыдущее':<12}{'Текущее':<10}{'Использовано':<14}{'К оплате':<10}{'Ср. цена m^3'}")
print(f"{prev_val:<12}{curr_val:<10}{used:<14}{cost:<10.2f}{avg_price:<10.2f}")